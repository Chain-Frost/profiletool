"""Summarise real local Pyright JSON diagnostics by cause and source file.

Works without QGIS. Uses only the report generated by the user's own QGIS
development environment; does not fabricate QGIS stubs or suppress checks.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import cast


def _relative_file(value: str) -> str:
    """Remove local directory prefixes from paths in shareable summaries."""
    normalised = value.replace("\\", "/")
    # Repeated slashes may appear in copied Windows/raw-string paths.
    while "//" in normalised:
        normalised = normalised.replace("//", "/")
    marker = "/profiletool/"
    if marker in normalised:
        return normalised.rsplit(marker, 1)[-1]
    if not normalised:
        return "(unknown)"
    return normalised.rsplit("/", 1)[-1]


def _frequency(counter: Counter[str]) -> list[dict[str, str | int]]:
    """Produce deterministic, descending-count diagnostic groups."""
    return [
        {"name": name, "count": count} for name, count in sorted(counter.items(), key=lambda item: (-item[1], item[0]))
    ]


def summarise(payload: dict[str, object]) -> dict[str, object]:
    """Classify Pyright errors; retain the original full-report counts."""
    raw = payload.get("generalDiagnostics")
    if not isinstance(raw, list):
        msg = "Pyright JSON must contain a generalDiagnostics list."
        raise ValueError(msg)
    diagnostics = cast(list[object], raw)

    rules: Counter[str] = Counter()
    files: Counter[str] = Counter()
    levels: Counter[str] = Counter()
    import_errors: Counter[str] = Counter()
    for item in diagnostics:
        if not isinstance(item, dict):
            continue
        issue = cast(dict[str, object], item)
        severity = str(issue.get("severity", "unknown"))
        levels[severity] += 1
        if severity != "error":
            continue
        rule = str(issue.get("rule") or "(unclassified)")
        source = _relative_file(str(issue.get("file") or ""))
        rules[rule] += 1
        files[source] += 1
        if rule in {"reportMissingImports", "reportMissingModuleSource"}:
            import_errors[source] += 1

    summary = payload.get("summary")
    report_total: int | None = None
    if isinstance(summary, dict):
        metadata = cast(dict[str, object], summary)
        count = metadata.get("errorCount")
        if isinstance(count, int) and not isinstance(count, bool):
            report_total = count

    return {
        "reported_errors": report_total,
        "collected_errors": levels["error"],
        "by_severity": _frequency(levels),
        "by_rule": _frequency(rules),
        "by_file": _frequency(files),
        "unresolved_imports_by_file": _frequency(import_errors),
        "note": "Collected diagnostics only. No QGIS types are simulated or warnings suppressed.",
    }


def main() -> None:
    """Read the full local Pyright output and write a shareable summary."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="JSON output from pyright --outputjson")
    parser.add_argument("--output", type=Path, help="Optional output JSON summary file")
    args = parser.parse_args()
    raw = json.loads(args.input.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        msg = "Expected a JSON object from Pyright."
        raise ValueError(msg)
    result = summarise(cast(dict[str, object], raw))
    formatted = json.dumps(result, indent=2, ensure_ascii=False) + "\n"
    if args.output is not None:
        args.output.write_text(formatted, encoding="utf-8")
    print(formatted, end="")


if __name__ == "__main__":
    main()
