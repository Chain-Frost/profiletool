r"""Export OSGeo4W's initialized environment for VS Code Python tools.

Run with C:\\OSGeo4W\\bin\\python-qgis.bat scripts\\write_qgis_env.py.
"""

import os
from pathlib import Path

ENVIRONMENT_KEYS = (
    "OSGEO4W_ROOT",
    "PYTHONHOME",
    "PYTHONPATH",
    "PYTHONUTF8",
    "PATH",
    "QGIS_PREFIX_PATH",
    "QT_PLUGIN_PATH",
    "QTWEBENGINE_RESOURCES_PATH",
    "GDAL_DATA",
    "GDAL_DRIVER_PATH",
    "GDAL_FILENAME_IS_UTF8",
    "PROJ_LIB",
    "PROJ_DATA",
)

if not os.environ.get("QGIS_PREFIX_PATH"):
    message = "Run this script using OSGeo4W's python-qgis.bat launcher."
    raise SystemExit(message)

root = Path(__file__).resolve().parents[1]
destination = root / ".vscode" / "qgis.env"
destination.parent.mkdir(exist_ok=True)
lines = ["# Generated by scripts/write_qgis_env.py; refresh after OSGeo4W updates."]
for key in ENVIRONMENT_KEYS:
    if key in os.environ:
        value = os.environ[key]
        if key == "PATH":
            value = os.pathsep.join([str(root / ".vscode" / "qgis-tools" / "bin"), value])
        if key == "PYTHONPATH":
            paths = [
                str(root / ".vscode" / "qgis-tools"),
                str(Path(os.environ["QGIS_PREFIX_PATH"]) / "python" / "plugins"),
                value,
            ]
            value = os.pathsep.join(paths)
        lines.append(f"{key}={value}")
destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {destination}")
